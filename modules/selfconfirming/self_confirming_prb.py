# --------------------------------------------------------------------------- #
# Endpoint: bistable adaptive-camera response operator                        #
# --------------------------------------------------------------------------- #
@dataclass
class Endpoint:
    """Hidden, stateful, bistable demand generator (an adaptive inspection camera).

    LOW mode: reduced fidelity / local processing -> small demand, poor quality.
    HIGH mode: full-fidelity edge offload -> large demand, high quality, reached
    only if sustained delivered service can feed it. Hysteresis holds the mode.
    The RAN never observes mode or quality.
    """

    d_low: float = 0.10          # demand per unit workload in low mode
    d_high: float = 1.00         # demand per unit workload in high mode; sensitivity = d_high/d_low
    up_thresh: float = 0.92      # headroom (service / high-mode need) to trigger upgrade
    down_thresh: float = 0.55    # sustain ratio below which it drops back (hysteresis)
    delay: int = 6              # adaptation delay (EMA window the endpoint integrates over)
    u_low: float = 0.30          # inspection utility in low mode
    u_high: float = 1.00         # inspection utility in high mode, fully served

    def __post_init__(self):
        self.reset()

    def reset(self, mode: int = 0):
        self.mode = mode
        self._ema_headroom = 0.0
        self._ema_sustain = 1.0
        self._alpha = 2.0 / (self.delay + 1.0)

    def target_demand(self, workload: float) -> float:
        return workload * (self.d_high if self.mode == 1 else self.d_low)

    def step(self, service: float, workload: float):
        """Advance one interval. Returns (measured_demand, utility, served_ratio)."""
        need_high = workload * self.d_high
        need_now = self.target_demand(workload)

        headroom = service / max(need_high, 1e-9)
        sustain = min(1.0, service / max(need_now, 1e-9))

        self._ema_headroom += self._alpha * (headroom - self._ema_headroom)
        self._ema_sustain += self._alpha * (sustain - self._ema_sustain)

        if self.mode == 0 and self._ema_headroom >= self.up_thresh:
            self.mode = 1
        elif self.mode == 1 and self._ema_sustain < self.down_thresh:
            self.mode = 0

        need_now = self.target_demand(workload)
        served_ratio = min(1.0, service / max(need_now, 1e-9))
        measured_demand = min(need_now, service)
        utility = (self.u_high if self.mode == 1 else self.u_low) * served_ratio
        return measured_demand, utility, served_ratio


@dataclass
class System:
    endpoint: Endpoint
    capacity: float = 1.20       # deliverable rate at theta = 1.0 (demand units)
    workload: float = 1.00       # exogenous task intensity (lambda)
    sla_floor: float = 0.08      # min PRB share guaranteeing base low-mode rate
    theta_max: float = 1.00      # max share available to this slice (scarcity knob)

    def service(self, theta: float, channel: float = 1.0) -> float:
        return theta * self.capacity * channel


# --------------------------------------------------------------------------- #
# Controllers (consume only network-observable measured demand)               #
# --------------------------------------------------------------------------- #
@dataclass
class ExoAllocator:
    """Demand-tracking allocator: forecast measured demand, serve it + margin.

    Anchored to measured demand, which in low mode is small, so it never
    provisions enough sustained service to cross the upgrade threshold. No
    margin escapes this, because the anchor itself is suppressed.
    """
    margin: float = 0.15
    ema: float = 2.0 / (8 + 1)
    name: str = "A_exo (demand-tracking)"

    def reset(self, sys: System):
        self._dhat = sys.endpoint.d_low * sys.workload

    def act(self, sys: System, last_measured: float) -> float:
        self._dhat += self.ema * (last_measured - self._dhat)
        theta = self._dhat * (1.0 + self.margin) / sys.capacity
        return float(np.clip(theta, sys.sla_floor, sys.theta_max))


@dataclass
class EndoAllocator:
    """Cultivation allocator: treats influence on future demand as a lever.

    Same demand-serving base, plus a bounded, SLA-safe probe. When a slice
    looks persistently low-demand and has not been tested recently, it lifts
    allocation just past the level that feeds the high mode, held longer than
    the adaptation delay. If measured demand rises (a latent high mode was
    revealed) it latches the estimate up so the base allocation immediately
    SUSTAINS the newly created demand. If nothing moves, it reverts. Probing
    never drops below the SLA floor and is capped at theta_max.
    """
    margin: float = 0.15
    ema: float = 2.0 / (8 + 1)
    probe_period: int = 45
    name: str = "A_endo (cultivation)"

    def reset(self, sys: System):
        self._dhat = sys.endpoint.d_low * sys.workload
        self._t = 0
        self._probe_left = 0
        self._probe_len = sys.endpoint.delay * 4
        self._baseline = None
        self._probe_theta = min(
            sys.theta_max,
            (sys.endpoint.up_thresh * sys.workload * sys.endpoint.d_high) / sys.capacity + 0.03,
        )

    def act(self, sys: System, last_measured: float) -> float:
        # Latch: if a probe revealed higher demand, snap the estimate up so the
        # base allocation sustains it despite EMA lag.
        if self._probe_left > 0 and self._baseline is not None:
            if last_measured > 1.6 * self._baseline:
                self._dhat = max(self._dhat, last_measured)

        self._dhat += self.ema * (last_measured - self._dhat)
        self._t += 1
        base = float(np.clip(self._dhat * (1.0 + self.margin) / sys.capacity,
                             sys.sla_floor, sys.theta_max))
        looks_low = self._dhat < 0.5 * sys.workload * sys.endpoint.d_high

        if self._probe_left > 0:
            self._probe_left -= 1
            return max(base, self._probe_theta)
        if looks_low and self._t % self.probe_period == 0:
            self._baseline = max(self._dhat, 1e-6)
            self._probe_left = self._probe_len
            return max(base, self._probe_theta)
        return base


@dataclass
class StaticAllocator:
    theta: float = 0.2
    name: str = "static"

    def reset(self, sys: System):
        pass

    def act(self, sys: System, last_measured: float) -> float:
        return float(np.clip(self.theta, sys.sla_floor, sys.theta_max))


# --------------------------------------------------------------------------- #
# Simulation driver                                                           #
# --------------------------------------------------------------------------- #
def run_closed_loop(sys: System, controller, steps=400, init_mode=0,
                    channel_trace=None, probe_override=None):
    sys.endpoint.reset(mode=init_mode)
    controller.reset(sys)
    thetas, demands, utils, modes = [], [], [], []
    last_measured = sys.endpoint.d_low * sys.workload
    for t in range(steps):
        ch = 1.0 if channel_trace is None else channel_trace[t % len(channel_trace)]
        theta = controller.act(sys, last_measured)
        if probe_override is not None:
            theta = probe_override(t, theta)
        md, u, _ = sys.endpoint.step(sys.service(theta, ch), sys.workload)
        last_measured = md
        thetas.append(theta); demands.append(md); utils.append(u); modes.append(sys.endpoint.mode)
    return {k: np.array(v) for k, v in
            dict(theta=thetas, demand=demands, util=utils, mode=modes).items()}


def steady_state(sys: System, theta: float, init_mode: int, steps=150):
    sys.endpoint.reset(mode=init_mode)
    md = u = 0.0
    for _ in range(steps):
        md, u, _ = sys.endpoint.step(sys.service(theta), sys.workload)
    return md, u


# --------------------------------------------------------------------------- #
# Experiments                                                                 #
# --------------------------------------------------------------------------- #
def exp1_landscape(sys: System, n=60):
    thetas = np.linspace(sys.sla_floor, sys.theta_max, n)
    up = np.array([steady_state(sys, th, 0) for th in thetas])
    dn = np.array([steady_state(sys, th, 1) for th in thetas])
    return thetas, up[:, 0], up[:, 1], dn[:, 0], dn[:, 1]


def exp3_probe(reps=80, seed=0):
    """Two traces with identical current load; one bounded probe separates them."""
    rng = np.random.default_rng(seed)
    ep = Endpoint()
    hold = ep_hold = 0.10                      # stingy but SLA-safe operating point
    cap = 1.20
    probe_theta = min(1.0, (ep.up_thresh * ep.d_high) / cap + 0.03)
    p0, plen = 30, ep.delay * 5

    def probe(t, th):
        return probe_theta if p0 <= t < p0 + plen else hold

    passive_low, passive_supp, resp_low, resp_supp = [], [], [], []
    for _ in range(reps):
        # Genuinely low: a flat, non-bistable endpoint whose demand stays ~0.10.
        sys_low = System(endpoint=Endpoint(d_low=0.10, d_high=0.10), capacity=cap, workload=1.0)
        # Suppressed: bistable endpoint, full workload, held in low mode -> also ~0.10.
        sys_supp = System(endpoint=Endpoint(), capacity=cap, workload=1.0)
        for sysx, pas, resp in ((sys_low, passive_low, resp_low),
                                (sys_supp, passive_supp, resp_supp)):
            out = run_closed_loop(sysx, StaticAllocator(theta=hold),
                                  steps=p0 + plen + ep.delay * 3, init_mode=0,
                                  probe_override=probe)
            dem = out["demand"] + rng.normal(0, 0.012, size=out["demand"].shape)
            pre = dem[p0 - 6:p0].mean()
            post = dem[p0 + plen - ep.delay: p0 + plen].max()
            pas.append(pre); resp.append(post - pre)

    a = dict(passive_low=np.array(passive_low), passive_supp=np.array(passive_supp),
             resp_low=np.array(resp_low), resp_supp=np.array(resp_supp))

    def best_acc(x, y):
        v = np.concatenate([x, y]); lab = np.concatenate([np.zeros_like(x), np.ones_like(y)])
        return max(max(((v <= t) == lab).mean(), ((v > t) == lab).mean())
                   for t in np.linspace(v.min(), v.max(), 300))

    a["passive_acc"] = best_acc(a["passive_low"], a["passive_supp"])
    a["probe_acc"] = best_acc(a["resp_low"], a["resp_supp"])
    return a


def escape_gap(sys: System, seeds=6, steps=500):
    """Mean tail utility gap (endo - exo) over noisy channel realizations."""
    gaps = []
    for s in range(seeds):
        ch = 1.0 + np.random.default_rng(s).normal(0, 0.03, steps)
        exo = run_closed_loop(sys, ExoAllocator(), steps=steps, channel_trace=ch)
        endo = run_closed_loop(sys, EndoAllocator(), steps=steps, channel_trace=ch)
        gaps.append(endo["util"][-120:].mean() - exo["util"][-120:].mean())
    return float(np.mean(gaps))


def exp4_region(base: System):
    sens = [1.5, 2, 3, 4, 6, 8, 10]
    g_sens = [escape_gap(replace(base, endpoint=replace(base.endpoint, d_high=base.endpoint.d_low * s)))
              for s in sens]
    scar = [1.0, 0.9, 0.82, 0.75, 0.68, 0.6]
    g_scar = [escape_gap(replace(base, theta_max=tm)) for tm in scar]
    mem = [2, 4, 6, 9, 12, 16]
    g_mem = [escape_gap(replace(base, endpoint=replace(base.endpoint, delay=d))) for d in mem]
    return dict(sens=(sens, g_sens), scar=(scar, g_scar), mem=(mem, g_mem))


