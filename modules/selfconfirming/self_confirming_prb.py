    print(f"[Exp4] gap vs scarcity    {e4['scar'][0]} = {[round(x,2) for x in e4['scar'][1]]}")
    print(f"[Exp4] gap vs memory      {e4['mem'][0]} = {[round(x,2) for x in e4['mem'][1]]}")

    ok = (u_endo - u_exo > 0.3 and e3["passive_acc"] < 0.65 and e3["probe_acc"] > 0.9)
