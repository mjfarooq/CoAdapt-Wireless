    endo = run_closed_loop(System(endpoint=Endpoint()), EndoAllocator(), steps=400)
    shi = run_closed_loop(System(endpoint=Endpoint()),
                          StaticAllocator(theta=0.85, name="static-high (oracle)"), steps=400)
    u_exo, u_endo = exo["util"][-100:].mean(), endo["util"][-100:].mean()
    a_exo, a_endo = exo["theta"][-100:].mean(), endo["theta"][-100:].mean()

    e3 = exp3_probe()
    e4 = exp4_region(System(endpoint=Endpoint()))

