    ax[1].plot(endo["util"], color="#27ae60", lw=1.8, label=f"A_endo  escapes (U={u_endo:.2f})")
    ax[1].plot(shi["util"], color="#7f8c8d", ls="--", lw=1, label="static-high (oracle)")
    ax[1].set_title("B. Same start, same endpoint\nthe demand-tracker traps itself")
    ax[1].set_xlabel("control interval"); ax[1].set_ylabel("inspection utility")
