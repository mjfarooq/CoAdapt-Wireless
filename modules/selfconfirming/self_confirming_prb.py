"""
Self-Confirming Allocation under Endogenous Demand -- PRB-level reference simulation.

Tier-zero experiment for the CoAdapt CAREER premise:

    A utility-maximizing allocator that treats slice demand as EXOGENOUS locks
    into a self-confirming, degraded operating point when the endpoint's demand
    is generated by a bistable (threshold + hysteresis) adaptation policy. An
    allocator that treats its own influence on future demand as a control lever
    (cultivation) escapes the trap.

Self-contained abstraction of the InspectCell PRB layer. No OAI / Isaac Sim
dependency, so it runs on a laptop and produces the figures that carry Thrust 1.

    fig_self_confirming.png   3 panels:
        A  measured hysteresis landscape R(theta), two stable branches
        B  closed-loop trajectories: demand-tracker locks in, cultivator escapes
        C  two traces with identical current load, split by one bounded probe
    fig_trap_region.png       when the trap exists (gap vs sensitivity/scarcity/memory)

The endpoint mode and inspection utility are APPLICATION-SIDE ground truth used
only for validation. The allocators consume only NETWORK-OBSERVABLE signals
(allocation-tagged measured demand), matching the identifiability discipline in
the proposal.

Run:  python3 self_confirming_prb.py
"""

